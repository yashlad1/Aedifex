"""The bill of quantities for the synthetic project: eleven trade groups, ~180 priced items.

Authored rather than generated at random, for two reasons. A quantity surveyor reading it should
recognise the trade breakdown of a G+4 residential tower, because the bundle's second job is to be
shown to one; and the item numbers the defect specification names have to exist, which a random
catalogue cannot guarantee.

Rates are representative of Indian building work and are **not** taken from any published schedule.
Copying CPWD DSR figures would make the file a derivative of a specific edition and would invite the
exact confusion Tier 5 exists to prevent — a synthetic document that looks sourced. They are round,
plausible, and fictional.

Quantities follow a real building's proportions: concrete and steel dominate the structure, finishes
dominate the item *count*, and the finishing trades carry the small repetitive lines where
measurement errors actually live.
"""

from __future__ import annotations

from dataclasses import dataclass
from decimal import Decimal
from typing import Final

__all__ = ["CATALOGUE", "BoqItem", "TradeGroup", "contract_value", "item_by_number", "items"]


@dataclass(frozen=True, slots=True)
class BoqItem:
    """One priced line of the contract bill."""

    number: str
    description: str
    unit: str
    quantity: Decimal
    rate: Decimal
    first_period: int
    """The RA bill in which this trade first appears. Structure early, finishes late."""

    last_period: int
    """The RA bill by which it is complete, absent a planted defect."""

    @property
    def amount(self) -> Decimal:
        return (self.quantity * self.rate).quantize(Decimal("0.01"))


@dataclass(frozen=True, slots=True)
class TradeGroup:
    number: str
    title: str
    items: tuple[BoqItem, ...]


def _q(value: str) -> Decimal:
    return Decimal(value)


def _group(
    number: str,
    title: str,
    rows: tuple[tuple[str, str, str, str, str, int, int], ...],
) -> TradeGroup:
    """Build a group from compact tuples: (item, description, unit, qty, rate, first, last)."""
    return TradeGroup(
        number=number,
        title=title,
        items=tuple(
            BoqItem(
                number=item,
                description=description,
                unit=unit,
                quantity=_q(quantity),
                rate=_q(rate),
                first_period=first,
                last_period=last,
            )
            for item, description, unit, quantity, rate, first, last in rows
        ),
    )


