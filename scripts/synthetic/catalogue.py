def items() -> tuple[BoqItem, ...]:
    """Every priced item, in bill order."""
    return tuple(item for group in CATALOGUE for item in group.items)


def item_by_number(number: str) -> BoqItem:
    """One item, by its bill number. Raises rather than returning ``None``.

    A defect specification naming an item that does not exist is a defect in the specification, and
    it must stop the generator rather than silently plant nothing.
    """
    for item in items():
        if item.number == number:
            return item
    raise KeyError(f"no catalogue item numbered {number!r}")


def contract_value() -> Decimal:
    """The bill's own total, which every generated document must reconcile to."""
    return sum((item.amount for item in items()), start=Decimal("0.00"))
